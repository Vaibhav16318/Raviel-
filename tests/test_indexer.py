def test_indexer_preserves_metadata():
    store = InMemoryVectorStore()

    indexer = Indexer(
        embedder=FakeEmbedder(),
        vector_store=store,
    )

    records = [
        {
            "query_id": "q1",
            "query": "What is solar energy?",
            "Answer": "Solar energy comes from the sun.",
            "Eng_Query": "What is solar energy?",
            "Eng_Answer": "Solar energy comes from the sun.",
            "source_lang": "eng_Latn",
            "target_lang": "eng_Latn",
            "query_type": "factoid",
            "passages": {
                "English_passages": [
                    "Solar energy is renewable and comes from sunlight."
                ],
                "Translated_passages": [],
                "is_selected": [1],
            },
            "meta": {
                "source": "test",
                "category": "energy",
            },
        }
    ]

    indexer.index_records(records)

    results = store.search([1.0, 0.0, 0.0], top_k=1)

    result = results[0][0]

    assert result.metadata["source"] == "test"
    assert result.metadata["category"] == "energy"